import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const OUT = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, serviceWorkers: 'block' });
await ctx.route(/dolarapi|bluelytics/, r => r.fulfill({ json: { compra: 1400, venta: 1450, fechaActualizacion: new Date().toISOString() } }));
const p = await ctx.newPage();
await p.goto('http://localhost:8777/');
await p.waitForSelector('#btn-continuar');
await p.fill('#cli-nombre', 'María Gómez');
await p.click('#btn-continuar');
await p.waitForTimeout(500);
await p.screenshot({ path: OUT + '/1-falta-telefono.png' });
await p.fill('#cli-telefono', '11 5555-1234');
await p.waitForTimeout(4000);
await p.click('#btn-continuar');
await p.click('#btn-agregar-item');
await p.click('.tipo-tile[data-tipo="vent-corr-2"]');
await p.waitForTimeout(300);
await p.locator('.item--abierto [data-campo="anchoCm"]').fill('');
await p.click('#btn-continuar');
await p.waitForTimeout(600);
await p.screenshot({ path: OUT + '/2-falta-medida.png' });
await p.locator('.item--abierto [data-campo="anchoCm"]').fill('150');
await p.waitForTimeout(4000);
await p.click('#btn-continuar');
await p.waitForTimeout(600);
await p.screenshot({ path: OUT + '/3-paso3-avance.png' });
await p.evaluate(() => {
  const pr = window.Almacenamiento.listar()[0];
  pr.estado = 'enviado';
  pr.enviadoEl = new Date(Date.now() - 6 * 864e5).toISOString();
  window.Almacenamiento.guardar(pr);
});
await p.reload(); await p.waitForSelector('#btn-continuar');
await p.click('.tab[data-vista="historial"]');
await p.waitForTimeout(400);
await p.screenshot({ path: OUT + '/4-guardados.png' });
await p.click('.historial-fila [data-accion="abrir"]');
await p.waitForTimeout(600);
await p.screenshot({ path: OUT + '/5-pregunta-acepto.png' });
console.log('pregunta visible:', await p.isVisible('#pregunta-acepto'));
await b.close();
