import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
const OUT = process.argv[2]; fs.mkdirSync(OUT, { recursive: true });
const dsf = Number(process.argv[3] || 1);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: dsf, serviceWorkers: 'block' });
await ctx.route(/dolarapi|bluelytics/, r => r.fulfill({ json: { compra: 1400, venta: 1450, fechaActualizacion: new Date().toISOString() } }));
const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
let fallas = 0; const ok = (c, m) => { console.log((c ? 'OK   ' : 'FALLA') + ' ' + m); if (!c) fallas++; };
await p.goto('http://localhost:8777/'); await p.waitForSelector('#btn-continuar');
await p.click('.tab[data-vista="precios"]'); await p.waitForTimeout(400);
await p.screenshot({ path: OUT + '/p1-menu.png' });
const alto = await p.evaluate(() => document.documentElement.scrollHeight);
ok(alto < 1600, 'el menú de Precios entra en ~2 pantallas: ' + alto + ' px');
await p.click('[data-abrir="aberturas"]'); await p.waitForTimeout(300);
ok(await p.textContent('#titulo-vista') === 'Aberturas' && await p.isVisible('#btn-atras'), 'abre Aberturas con título y botón atrás');
await p.screenshot({ path: OUT + '/p2-aberturas.png' });
const altoAb = await p.evaluate(() => document.documentElement.scrollHeight);
console.log('alto aberturas', altoAb);
// editar precio inline
const fila = p.locator('#tabla-tipologias .fila-precio').first();
await fila.locator('.fila-precio__principal input').fill('123456');
await p.waitForTimeout(300);
const guardado = await p.evaluate(() => window.Almacenamiento.cargarPrecios().tipologias[0].precioM2);
ok(guardado === 123456, 'el precio del renglón se guarda: ' + guardado);
await fila.locator('.fila-precio__nombre').click();
ok(await fila.locator('.fila-precio__detalle').isVisible(), 'tocando el nombre se abre el detalle');
await fila.locator('[data-campo="nombre"]').fill('Ventana X');
ok(await fila.locator('[data-nombre]').textContent() === 'Ventana X', 'el nombre del renglón se actualiza al escribir');
await p.screenshot({ path: OUT + '/p3-detalle.png' });
// atrás del celular
await p.goBack(); await p.waitForTimeout(300);
ok(await p.isVisible('#menu-precios') && await p.textContent('#titulo-vista') === 'Precios', 'el atrás del celular vuelve al menú');
await p.click('[data-abrir="empresa"]'); await p.waitForTimeout(200);
await p.screenshot({ path: OUT + '/p4-empresa.png' });
await p.click('#btn-atras'); await p.waitForTimeout(300);
ok(await p.isVisible('#menu-precios'), 'el botón ‹ vuelve al menú');
await p.click('[data-abrir="lineas"]');
await p.click('.tab[data-vista="presupuesto"]'); await p.click('.tab[data-vista="precios"]'); await p.waitForTimeout(200);
ok(await p.isVisible('#menu-precios'), 'la pestaña Precios siempre arranca en el menú');
await p.click('[data-abrir="vidrios"]'); await p.waitForTimeout(200);
await p.click('#tabla-vidrios [data-accion="agregar"]'); await p.waitForTimeout(200);
ok(await p.evaluate(() => document.activeElement && document.activeElement.dataset.campo === 'nombre'), 'agregar un vidrio lo abre con el cursor en el nombre');
await p.click('#btn-atras'); await p.waitForTimeout(300);
await p.click('.tab[data-vista="presupuesto"]'); await p.waitForTimeout(300);
await p.screenshot({ path: OUT + '/p5-paso1.png' });
ok(errs.length === 0, 'sin errores' + (errs.length ? ': ' + errs.join(' | ') : ''));
await b.close(); process.exitCode = fallas ? 1 : 0;
